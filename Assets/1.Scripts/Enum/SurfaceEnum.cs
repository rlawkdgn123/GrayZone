/// <summary>
/// 필드 구조물의 재질 종류입니다. 표면 피드백과 소음 차폐가 공유하는 단일 식별 축입니다.
/// </summary>
/// <remarks>
/// <para>
/// 소비자마다 필요한 해상도가 다릅니다. 탄착 이펙트는 석재와 벽돌을 같은 돌로 퉁쳐도 되지만 소음 차폐는
/// 둘을 구분해야 할 수 있습니다. 그래서 <b>이 열거형은 모든 소비자 중 가장 세밀한 쪽에 맞춰 잘게 두고,
/// 퉁치는 것은 각 소비자가 자기 에셋에서 여러 값을 나열해 선언합니다.</b>
/// 축을 소비자 수만큼 만들면 같은 벽이 축마다 다르게 분류돼도 아무도 잡지 못합니다.
/// </para>
/// <para>
/// <b>값을 10씩 띄운 이유</b>: 나중에 사이에 새 재질을 끼워 넣어도 이미 직렬화된 씬·프리팹의 값이 밀리지
/// 않게 하기 위해서입니다. 자동 번호였다면 중간 삽입 한 번에 필드 전체의 재질이 조용히 한 칸씩 어긋납니다.
/// 새 재질은 되도록 뒤에 붙이고, 사이에 넣어야 하면 비어 있는 번호를 쓸 것.
/// </para>
/// <para>
/// <b>기획 미확정 - 임시 목록입니다.</b> 실제 재질 종류는 아트·기획 확정이 필요하며, 확정되면 이 목록을
/// 그쪽 기준으로 다시 맞춰야 합니다. 지금 값은 시스템을 돌려 보기 위한 최소 집합입니다.
/// </para>
/// </remarks>
public enum SurfaceMaterialType
{
    /// <summary>재질을 지정하지 않은 구조물입니다. 각 소비자의 기본값을 씁니다.</summary>
    Unknown = 0,

    /// <summary>콘크리트입니다.</summary>
    Concrete = 10,

    /// <summary>석재입니다.</summary>
    Stone = 20,

    /// <summary>금속입니다.</summary>
    Metal = 30,

    /// <summary>목재입니다.</summary>
    Wood = 40,

    /// <summary>흙바닥입니다.</summary>
    Dirt = 50,

    /// <summary>금속 관람석입니다.</summary>
    MetalBleacher = 60,

    /// <summary>금속 캣워크입니다.</summary>
    MetalCatwalk = 70,

    /// <summary>밟을 수 있는 금속 환기 구조물입니다.</summary>
    MetalVent = 80,

    /// <summary>세라믹 타일 바닥입니다.</summary>
    CeramicTile = 90,
}
